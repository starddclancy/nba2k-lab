using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Nba2k27Editor.Core.Editing;

/// <summary>A saved player or face kept in the local library (one JSON file per entry).</summary>
public sealed record LibraryEntry(
    string Id, string Name, string Kind, string Created, string SourcePlayer, int FieldCount, string Notes);

/// <summary>
/// Local custom-player and face library. Entries are raw field values keyed like the player
/// snapshot ("Appearance/Head/HEADPRESET"), so applying one reuses the normal player edit path.
/// </summary>
public static class PlayerLibrary
{
    public const string Format = "nba2k27-player-library/1";
    public const string ExportFormat = "nba2k27-player-export/1";
    public static readonly string[] Kinds = { "player", "face" };

    // The face model reference and whether the game falls back to the created-player face.
    private static readonly string[] FaceIds =
    {
        "Advanced/IDs/GRAPHICID", "Advanced/Flags/LOADASCREATEDPLAYERIFARTISMISSING",
    };

    /// <summary>
    /// Face fields: every Appearance group except clothing presentation, plus the face model ID.
    /// Portrait photo IDs stay with the player, so a face patch does not show the donor's photo.
    /// </summary>
    public static bool IsFaceField(string key) =>
        (key.StartsWith("Appearance/", StringComparison.Ordinal)
            && !key.StartsWith("Appearance/Presentation/", StringComparison.Ordinal))
        || FaceIds.Contains(key, StringComparer.Ordinal);

    /// <summary>Fields that identify a record and must never be copied onto another player.</summary>
    public static bool IsIdentityField(string key) =>
        key is "Advanced/IDs/UNIQUEID" or "Advanced/IDs/PRESERVEDID" or "Advanced/IDs/FRANCHISEPLAYERDATAINDEX"
        || key.StartsWith("Stats/", StringComparison.Ordinal)
        || key.StartsWith("Contract/", StringComparison.Ordinal)
        || key.StartsWith("Vitals/Team/", StringComparison.Ordinal);

    /// <summary>Which saved fields an apply touches for the requested scope.</summary>
    public static bool InScope(string key, string scope) => scope switch
    {
        "face" => IsFaceField(key),
        "player" => !IsIdentityField(key),
        _ => throw new ArgumentException("Unknown library scope: " + scope),
    };

    public static string NewId(DateTimeOffset now) =>
        now.ToString("yyyyMMdd-HHmmss", CultureInfo.InvariantCulture) + "-" + Guid.NewGuid().ToString("N")[..8];

    /// <summary>Ids are generated by NewId; anything else could escape the library folder.</summary>
    public static bool ValidId(string id) =>
        id.Length is > 0 and <= 64 && id.All(character => char.IsAsciiLetterOrDigit(character) || character == '-');

    public static string PathFor(string directory, string id) =>
        ValidId(id) ? Path.Combine(directory, id + ".json") : throw new ArgumentException("Invalid library id");

    public static JsonObject Create(
        string id, string name, string kind, string sourcePlayer, string notes, IEnumerable<KeyValuePair<string, JsonNode?>> values,
        DateTimeOffset now)
    {
        if (!Kinds.Contains(kind))
        {
            throw new ArgumentException("Unknown library kind: " + kind);
        }
        string trimmed = (name ?? string.Empty).Trim();
        if (trimmed.Length is 0 or > 80)
        {
            throw new ArgumentException("Library name must be 1-80 characters");
        }
        var kept = new JsonObject();
        foreach (var pair in values.Where(pair => InScope(pair.Key, kind)).OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            kept[pair.Key] = pair.Value?.DeepClone();
        }
        if (kept.Count == 0)
        {
            throw new ArgumentException("No fields to save for this kind");
        }
        return new JsonObject
        {
            ["format"] = Format,
            ["id"] = id,
            ["name"] = trimmed,
            ["kind"] = kind,
            ["created"] = now.ToString("yyyy-MM-ddTHH:mm:sszzz", CultureInfo.InvariantCulture),
            ["sourcePlayer"] = sourcePlayer,
            ["notes"] = notes.Length > 2000 ? notes[..2000] : notes,
            ["fieldCount"] = kept.Count,
            ["values"] = kept,
        };
    }

    /// <summary>Parse a library entry, or an editor player export converted to a "player" entry.</summary>
    public static (LibraryEntry Entry, JsonObject Values) Parse(string text, string fallbackId)
    {
        JsonObject document;
        try
        {
            document = JsonNode.Parse(text)?.AsObject() ?? throw new InvalidDataException("Empty library file");
        }
        catch (JsonException exc)
        {
            throw new InvalidDataException("Invalid library JSON: " + exc.Message, exc);
        }
        string format = document["format"]?.GetValue<string>() ?? string.Empty;
        if (document["values"] is not JsonObject values || values.Count == 0)
        {
            throw new InvalidDataException("Library file has no values");
        }
        if (format == ExportFormat)
        {
            string name = document["name"]?.GetValue<string>() ?? "player";
            return (new LibraryEntry(fallbackId, name, "player", document["time"]?.GetValue<string>() ?? string.Empty,
                name, values.Count, string.Empty), values);
        }
        if (format != Format)
        {
            throw new InvalidDataException("Unsupported library format: " + format);
        }
        string kind = document["kind"]?.GetValue<string>() ?? string.Empty;
        if (!Kinds.Contains(kind))
        {
            throw new InvalidDataException("Unsupported library kind: " + kind);
        }
        string id = document["id"]?.GetValue<string>() ?? fallbackId;
        return (new LibraryEntry(
            ValidId(id) ? id : fallbackId,
            document["name"]?.GetValue<string>() ?? id, kind,
            document["created"]?.GetValue<string>() ?? string.Empty,
            document["sourcePlayer"]?.GetValue<string>() ?? string.Empty,
            values.Count,
            document["notes"]?.GetValue<string>() ?? string.Empty), values);
    }

    public static void Save(string directory, JsonObject document)
    {
        Directory.CreateDirectory(directory);
        string path = PathFor(directory, document["id"]!.GetValue<string>());
        string temporary = Path.ChangeExtension(path, ".tmp");
        File.WriteAllText(temporary, document.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n",
            new UTF8Encoding(false));
        File.Move(temporary, path, overwrite: true);
    }

    public static IReadOnlyList<LibraryEntry> List(string directory)
    {
        if (!Directory.Exists(directory))
        {
            return Array.Empty<LibraryEntry>();
        }
        var entries = new List<LibraryEntry>();
        foreach (string path in Directory.EnumerateFiles(directory, "*.json"))
        {
            try
            {
                entries.Add(Parse(File.ReadAllText(path), Path.GetFileNameWithoutExtension(path)).Entry);
            }
            catch (Exception exc) when (exc is InvalidDataException or IOException or InvalidOperationException)
            {
                // A damaged file must not hide the rest of the library.
            }
        }
        return entries.OrderByDescending(entry => entry.Created, StringComparer.Ordinal).ToList();
    }
}
